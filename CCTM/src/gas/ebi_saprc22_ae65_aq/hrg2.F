     &   +    5.0000D-02 * RXRAT(   698 )      ! RPNO3_OH=0.5000D-01*OH+...
     &   +                 RXRAT(   700 )      ! RPNO3=OH+0.1400D+00*HO2+...
     &   +    9.0000D-02 * RXRAT(   711 )      ! R2NO3_HV=0.9000D-01*OH+...
     &   +    6.0000D-02 * RXRAT(   716 )      ! RUOOH_OH=0.6000D-01*OH+...
