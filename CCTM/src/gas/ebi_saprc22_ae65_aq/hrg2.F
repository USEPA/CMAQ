      R4_5 =                 RKI(    30 ) * YC ( NO           )   ! HO2+NO=OH+NO2
     &     +                 RKI(    37 ) * YC ( O3           )   ! HO2+O3=OH
     &     +                 RKI(    40 ) * YC ( NO3          )   ! HO2+NO3=OH+NO2
     &     +    5.0000D-01 * RKI(    85 ) * YC ( MECO3        )   ! HO2+MECO3=...
     &     +    5.0000D-01 * RKI(    90 ) * YC ( BZCO3        )   ! HO2+BZCO3=...
     &     +    5.0000D-01 * RKI(   458 ) * YC ( R2CO3        )   ! HO2+R2CO3=...
     &     +    5.0000D-01 * RKI(   465 ) * YC ( MACO3        )   ! HO2+MACO3=...

      R4_5  = R4_5 * DTC

