     &   +    4.0000D-02 * RXRAT(   724 )      ! ROOH_OH=0.4000D-01*OH+...
     &   +                 RXRAT(   726 )      ! ROOH=OH+0.7400D+00*HO2+...
     &   +    2.0000D-02 * RXRAT(   728 )      ! AFG1_OH=0.2000D-01*OH+...
     &   +    3.0000D-01 * RXRAT(   730 )      ! AFG1=0.3000D+00*OH+0.9400D+...
     &   +    6.7000D-01 * RXRAT(   731 )      ! AFG1_HV=0.6700D+00*OH+...
     &   +                 RXRAT(   736 )      ! AFG2A=OH+0.9100D+00*MEO2+...
     &   +    8.8000D-01 * RXRAT(   740 )      ! AFG2B=0.8800D+00*OH+...
     &   +    9.0000D-02 * RXRAT(   741 )      ! AFG2B_HV=0.9000D-01*OH+...
     &   +    1.9000D-01 * RXRAT(   749 )      ! APANS+O3=0.1900D+00*OH+...

      P4 = YC0( OH ) + P4 * DTC

c..Production of HO2 from OH ( r5,4 terms )
      R5_4 =                 RKI(    26 ) * YC ( NO3          )   ! OH+NO3=HO2+NO2
     &     +                 RKI(    29 ) * YC ( O3           )   ! OH+O3=HO2
     &     +                 RKI(    43 ) * YC ( HO2H         )   ! OH+HO2H=HO2
     &     +                 RKI(    45 ) * YC ( CO           )   ! OH+CO=HO2+CO2
     &     +                 RKI(    46 )                         ! OH=HO2
     &     +                 RKI(   115 ) * YC ( SO2          )   ! OH+SO2=HO2+SULF+...
     &     +                 RKI(   119 ) * YC ( HCHO         )   ! OH+HCHO=HO2+CO
     &     +    7.0000D-01 * RKI(   125 ) * YC ( GLY          )   ! OH+GLY=0.7000D+...
     &     +    7.4100D-01 * RKI(   134 ) * YC ( NAPS         )   ! OH+NAPS=0.7410D+...
     &     +                 RKI(   135 ) * YC ( CATL3        )   ! OH+CATL3=HO2+OTHN
     &     +                 RKI(   137 ) * YC ( NAPPRD       )   ! OH+NAPPRD=HO2+OTHN
     &     +    2.0000D-02 * RKI(   501 ) * YC ( APINE        )   ! OH+APINE=0.2000D-...
     &     +    1.0000D-02 * RKI(   507 ) * YC ( BPINE        )   ! OH+BPINE=0.1000D-...
     &     +    3.3000D-01 * RKI(   513 ) * YC ( ACETL        )   ! OH+ACETL=0.3300D+...
     &     +    6.9000D-01 * RKI(   515 ) * YC ( BENZ         )   ! OH+BENZ=0.6900D+...
     &     +    4.1000D-01 * RKI(   516 ) * YC ( TOLU         )   ! OH+TOLU=0.4100D+...
     &     +    3.5000D-01 * RKI(   517 ) * YC ( OXYL         )   ! OH+OXYL=0.3500D+...
     &     +    2.1000D-01 * RKI(   518 ) * YC ( MXYL         )   ! OH+MXYL=0.2100D+...
     &     +    3.8000D-01 * RKI(   519 ) * YC ( PXYL         )   ! OH+PXYL=0.3800D+...
     &     +    1.8000D-01 * RKI(   520 ) * YC ( BZ123        )   ! OH+BZ123=0.1800D+...
     &     +    2.3000D-01 * RKI(   521 ) * YC ( BZ124        )   ! OH+BZ124=0.2300D+...
     &     +    1.7000D-01 * RKI(   522 ) * YC ( BZ135        )   ! OH+BZ135=0.1700D+...
     &     +    3.6000D-01 * RKI(   523 ) * YC ( C2BEN        )   ! OH+C2BEN=0.3600D+...
     &     +                 RKI(   525 ) * YC ( MEOH         )   ! OH+MEOH=HO2+HCHO
     &     +                 RKI(   526 ) * YC ( HCOOH        )   ! OH+HCOOH=HO2+CO2
     &     +    9.5000D-01 * RKI(   534 ) * YC ( ETOH         )   ! OH+ETOH=0.9500D+...
     &     +    2.0000D-01 * RKI(   535 ) * YC ( GLCHO        )   ! OH+GLCHO=0.2000D+...
     &     +    8.5000D-01 * RKI(   570 ) * YC ( PHEN         )   ! OH+PHEN=0.8500D+...
     &     +    2.7000D-01 * RKI(   575 ) * YC ( ALK4         )   ! OH+ALK4=0.2700D+...
     &     +    3.0000D-01 * RKI(   576 ) * YC ( ALK5         )   ! OH+ALK5=0.3000D+...
     &     +    1.6000D-01 * RKI(   579 ) * YC ( ALK6         )   ! OH+ALK6=0.1600D+...
     &     +    2.0000D-02 * RKI(   602 ) * YC ( TERP         )   ! OH+TERP=0.2000D-...
     &     +    5.0000D-02 * RKI(   612 ) * YC ( SESQ         )   ! OH+SESQ=0.5000D-...
     &     +    6.9000D-01 * RKI(   622 ) * YC ( BENX         )   ! OH+BENX=0.6900D+...
     &     +    2.7000D-01 * RKI(   623 ) * YC ( ARO1         )   ! OH+ARO1=0.2700D+...
     &     +    2.9000D-01 * RKI(   624 ) * YC ( ARO2         )   ! OH+ARO2=0.2900D+...
     &     +    7.5000D-01 * RKI(   627 ) * YC ( FURNS        )   ! OH+FURNS=0.7500D+...
     &     +    6.0000D-02 * RKI(   630 ) * YC ( STYRS        )   ! OH+STYRS=0.6000D-...
     &     +    2.0000D-02 * RKI(   632 ) * YC ( AMINS        )   ! OH+AMINS=0.2000D-...
     &     +    1.0000D-01 * RKI(   635 ) * YC ( RCHO         )   ! OH+RCHO=0.1000D+...
     &     +    2.2000D-01 * RKI(   638 ) * YC ( OLEA1        )   ! OH+OLEA1=0.2200D+...
     &     +    5.0000D-02 * RKI(   646 ) * YC ( OLEA2        )   ! OH+OLEA2=0.5000D-...
     &     +    5.6000D-01 * RKI(   658 ) * YC ( KET2         )   ! OH+KET2=0.5600D+...
     &     +    2.2000D-01 * RKI(   660 ) * YC ( LVKS         )   ! OH+LVKS=0.2200D+...
     &     +    1.3000D-01 * RKI(   667 ) * YC ( OLEP         )   ! OH+OLEP=0.1300D+...
     &     +    8.4000D-01 * RKI(   681 ) * YC ( CRES         )   ! OH+CRES=0.8400D+...
     &     +    7.8000D-01 * RKI(   683 ) * YC ( XYNL         )   ! OH+XYNL=0.7800D+...
     &     +    9.6000D-01 * RKI(   685 ) * YC ( CATL         )   ! OH+CATL=0.9600D+...
     &     +    5.0000D-02 * RKI(   687 ) * YC ( RCNO3        )   ! OH+RCNO3=0.5000D-...
     &     +    8.0000D-02 * RKI(   693 ) * YC ( RHNO3        )   ! OH+RHNO3=0.8000D-...
