     &      +    8.0000D-01 * RKI(    35 )                         ! HNO4=0.8000D+...

      R5_21 = R5_21 * DTC

c..Remaining HO2 production terms
      P5 =                 RXRAT(    67 )      ! MEO2+NO=HO2+HCHO+NO2
     &   +                 RXRAT(    69 )      ! MEO2+NO3=HO2+HCHO+NO2
     &   +    3.0000D-01 * RXRAT(    70 )      ! MEO2+SumRO2=0.3000D+00*HO2+...
     &   +    9.0000D-01 * RXRAT(    71 )      ! MEO2+SumRCO3=0.9000D+...
     &   +                 RXRAT(    72 )      ! ETO2+NO=HO2+NO2+MECHO
     &   +                 RXRAT(    74 )      ! ETO2+NO3=HO2+NO2+MECHO
     &   +    5.0000D-01 * RXRAT(    75 )      ! ETO2+SumRO2=0.5000D+00*HO2+...
     &   +    8.0000D-01 * RXRAT(    76 )      ! ETO2+SumRCO3=0.8000D+...
     &   +    2.0000D+00 * RXRAT(   117 )      ! HCHO=0.2000D+01*HO2+CO
     &   +                 RXRAT(   120 )      ! HCHO+NO3=HO2+HNO3+CO
     &   +    2.0000D+00 * RXRAT(   123 )      ! GLY=0.2000D+01*HO2+0.2000D+...
     &   +    7.0000D-01 * RXRAT(   126 )      ! GLY+NO3=0.7000D+00*HO2+...
     &   +    2.0000D+00 * RXRAT(   139 )      ! PHOT=0.2000D+01*HO2+...
     &   +                 RXRAT(   150 )      ! xHO2+NO=HO2+NO
     &   +                 RXRAT(   152 )      ! xHO2+NO3=HO2+NO3
     &   +    5.0000D-01 * RXRAT(   153 )      ! xHO2+SumRO2=0.5000D+00*HO2+...
     &   +                 RXRAT(   154 )      ! xHO2+SumRCO3=HO2+SumRCO3
     &   +                 RXRAT(   412 )      ! zR1NO3+NO3=HO2+KET2+NO3
     &   +    5.0000D-01 * RXRAT(   413 )      ! zR1NO3+SumRO2=0.5000D+...
     &   +                 RXRAT(   414 )      ! zR1NO3+SumRCO3=HO2+KET2+...
     &   +                 RXRAT(   417 )      ! zR2NO3+NO3=HO2+KET2+NO3
     &   +    5.0000D-01 * RXRAT(   418 )      ! zR2NO3+SumRO2=0.5000D+...
     &   +                 RXRAT(   419 )      ! zR2NO3+SumRCO3=HO2+KET2+...
     &   +                 RXRAT(   422 )      ! zRHNO3+NO3=HO2+KET2+NO3
     &   +    5.0000D-01 * RXRAT(   423 )      ! zRHNO3+SumRO2=0.5000D+...
     &   +                 RXRAT(   424 )      ! zRHNO3+SumRCO3=HO2+KET2+...
     &   +                 RXRAT(   427 )      ! zRCNO3+NO3=HO2+KET2+NO3
     &   +    5.0000D-01 * RXRAT(   428 )      ! zRCNO3+SumRO2=0.5000D+...
     &   +                 RXRAT(   429 )      ! zRCNO3+SumRCO3=HO2+KET2+...
