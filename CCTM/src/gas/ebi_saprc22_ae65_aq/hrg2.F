     &     +    1.2000D-01 * RKI(   697 ) * YC ( RPNO3        )   ! OH+RPNO3=0.1200D+...
     &     +    1.0000D-02 * RKI(   703 ) * YC ( RDNO3        )   ! OH+RDNO3=0.1000D-...
     &     +    1.0000D-02 * RKI(   707 ) * YC ( R1NO3        )   ! OH+R1NO3=0.1000D-...
