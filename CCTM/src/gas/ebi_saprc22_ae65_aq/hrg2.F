     &   +    5.0000D-02 * RXRAT(   668 )      ! OLEP_OH=0.5000D-01*OH+...
     &   +    6.1000D-01 * RXRAT(   670 )      ! OLEP+O3=0.6100D+00*OH+...
     &   +    1.7000D-01 * RXRAT(   671 )      ! OLEP_O3=0.1700D+00*OH+...
