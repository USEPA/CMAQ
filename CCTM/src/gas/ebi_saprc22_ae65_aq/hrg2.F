     &   +    1.0000D-02 * RXRAT(   502 )      ! APINE_OH=0.1000D-01*OH+...
     &   +    6.9000D-01 * RXRAT(   504 )      ! APINE+O3=0.6900D+00*OH+...
     &   +    4.0000D-02 * RXRAT(   508 )      ! BPINE_OH=0.4000D-01*OH+...
     &   +    3.9000D-01 * RXRAT(   510 )      ! BPINE+O3=0.3900D+00*OH+...
     &   +    2.0000D-02 * RXRAT(   511 )      ! BPINE+NO3=0.2000D-01*OH+...
     &   +                 RXRAT(   528 )      ! MEOOH=OH+HO2+HCHO
     &   +    7.0000D-02 * RXRAT(   537 )      ! GLCHO=0.7000D-01*OH+...
     &   +    1.5000D-01 * RXRAT(   546 )      ! ACRO+O3=0.1500D+00*OH+...
     &   +    2.2000D-01 * RXRAT(   548 )      ! ACRO=0.2200D+00*OH+0.4900D+...
     &   +    1.9000D-01 * RXRAT(   558 )      ! MACR+O3=0.1900D+00*OH+...
     &   +    4.5000D-01 * RXRAT(   562 )      ! MACR=0.4500D+00*OH+0.3000D+...
     &   +    1.8000D-01 * RXRAT(   564 )      ! MVK+O3=0.1800D+00*OH+...
     &   +                 RXRAT(   569 )      ! BUDAL=OH+HO2+MALAH
     &   +    2.6000D-01 * RXRAT(   583 )      ! OLE1+O3=0.2600D+00*OH+...
     &   +    4.6000D-01 * RXRAT(   587 )      ! OLE2+O3=0.4600D+00*OH+...
     &   +    1.0000D-02 * RXRAT(   588 )      ! OLE2_O3=0.1000D-01*OH+...
     &   +    5.8000D-01 * RXRAT(   593 )      ! OLE3+O3=0.5800D+00*OH+...
     &   +    7.2000D-01 * RXRAT(   597 )      ! OLE4+O3=0.7200D+00*OH+...
     &   +    6.0000D-02 * RXRAT(   603 )      ! TERP_OH=0.6000D-01*OH+...
     &   +    5.8000D-01 * RXRAT(   605 )      ! TERP+O3=0.5800D+00*OH+...
     &   +    6.0000D-02 * RXRAT(   606 )      ! TERP_O3=0.6000D-01*OH+...
     &   +    1.0000D-02 * RXRAT(   608 )      ! TERP+NO3=0.1000D-01*OH+...
     &   +    1.0000D-01 * RXRAT(   609 )      ! TERP_N3=0.1000D+00*OH+...
     &   +    7.0000D-02 * RXRAT(   613 )      ! SESQ_OH=0.7000D-01*OH+...
     &   +    6.6000D-01 * RXRAT(   615 )      ! SESQ+O3=0.6600D+00*OH+...
     &   +    7.0000D-02 * RXRAT(   616 )      ! SESQ_O3=0.7000D-01*OH+...
     &   +    2.0000D-02 * RXRAT(   618 )      ! SESQ+NO3=0.2000D-01*OH+...
     &   +    1.0000D-02 * RXRAT(   619 )      ! SESQ_N3=0.1000D-01*OH+...
     &   +    8.0000D-02 * RXRAT(   631 )      ! STYRS+O3=0.8000D-01*OH+...
     &   +    6.2000D-01 * RXRAT(   641 )      ! OLEA1+O3=0.6200D+00*OH+...
     &   +    4.3000D-01 * RXRAT(   645 )      ! OLEA1=0.4300D+00*OH+...
