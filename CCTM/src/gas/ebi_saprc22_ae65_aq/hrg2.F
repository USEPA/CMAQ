     &   +    5.2000D-01 * RXRAT(   649 )      ! OLEA2+O3=0.5200D+00*OH+...
     &   +    2.0000D-02 * RXRAT(   651 )      ! OLEA2_O3+NO=0.2000D-01*OH+...
     &   +    2.0000D-02 * RXRAT(   653 )      ! OLEA2_N3=0.2000D-01*OH+...
     &   +    1.5000D-01 * RXRAT(   655 )      ! OLEA2=0.1500D+00*OH+...
     &   +    1.4000D-01 * RXRAT(   656 )      ! OLEA2_HV=0.1400D+00*OH+...
     &   +    2.3000D-01 * RXRAT(   661 )      ! LVKS_OH=0.2300D+00*OH+...
